class User {
    int id;
    String name;
    String email;
    String password;
    String phone;
    String address;

    public User(int id, String name, String email, String password, String phone, String address) {
        this.id = id;
        this.name = name;
        this.email = email;
        this.password = password;
        this.phone = phone;
        this.address = address;
    }
}
