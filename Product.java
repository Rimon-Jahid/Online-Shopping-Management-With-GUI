
class Product {
    int code;
    String name;
    float price;
    String prodDate;
    String expireDate;
    String pic;

    public Product(int code, String name, float price, String prodDate, String expireDate,String pic) {
        this.code = code;
        this.name = name;
        this.price = price;
        this.prodDate = prodDate;
        this.expireDate = expireDate;
        this.pic = pic;
    }
}
